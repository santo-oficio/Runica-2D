import { spawn } from 'node:child_process';
import { writeFileSync } from 'node:fs';
const proc = spawn('C:/Program Files/Google/Chrome/Application/chrome.exe', ['--headless=new', '--remote-debugging-port=9334', '--no-first-run',
  `--user-data-dir=${process.env.TEMP}/selcdp`, '--window-size=1600,900', 'about:blank']);
const sleep = ms => new Promise(r => setTimeout(r, ms));
await sleep(2500);
const tabs = await (await fetch('http://127.0.0.1:9334/json')).json();
const ws = new WebSocket(tabs.find(t => t.type === 'page').webSocketDebuggerUrl);
await new Promise(r => ws.onopen = r);
let id = 0; const pend = new Map();
ws.onmessage = (m) => { const d = JSON.parse(m.data);
  if (d.id && pend.has(d.id)) { pend.get(d.id)(d.result); pend.delete(d.id); }
  if (d.method === 'Runtime.exceptionThrown') console.log('EXC', JSON.stringify(d.params.exceptionDetails).slice(0, 300)); };
const send = (method, params = {}) => new Promise(r => { const i = ++id; pend.set(i, r); ws.send(JSON.stringify({ id: i, method, params })); });
const ev = async (expr) => (await send('Runtime.evaluate', { expression: expr, returnByValue: true })).result?.value;
const shot = async (n) => { const r = await send('Page.captureScreenshot', { format: 'png' }); writeFileSync(`.tmp_chk/sel-${n}.png`, Buffer.from(r.data, 'base64')); };
const key = async (k, code) => { await send('Input.dispatchKeyEvent', { type: 'keyDown', key: k, code: code || k }); await send('Input.dispatchKeyEvent', { type: 'keyUp', key: k, code: code || k }); };
await send('Runtime.enable'); await send('Page.enable');
await send('Emulation.setDeviceMetricsOverride', { width: 1600, height: 900, deviceScaleFactor: 1, mobile: false });
await send('Page.navigate', { url: 'http://localhost:3000/seleccion-personaje.html' });
await sleep(9000);
await ev('confirmSelection()'); await sleep(700);
console.log('A', await ev('JSON.stringify({open:modalOpen,mode:modalMode,text:invalidText})')); await shot('none');
await key('Enter'); await sleep(500);
console.log('B closed', await ev('modalOpen'));
await ev('selected=2;render();confirmSelection()'); await sleep(700);
console.log('C', await ev('invalidText')); await shot('noname');
await key('Escape'); await sleep(400);
await ev("selected=null;typed='JAVIER';render();confirmSelection()"); await sleep(600);
console.log('D', await ev('invalidText'));
await key('Enter'); await sleep(400);
await ev("selected=1;render();confirmSelection()"); await sleep(700);
console.log('E', await ev('JSON.stringify({open:modalOpen,mode:modalMode})')); await shot('ok');
ws.close(); proc.kill(); process.exit(0);
